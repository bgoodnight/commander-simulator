"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const Dashboard=require("../web/pages/gorge_dashboard.js");
const root=path.resolve(__dirname,"../docs/deck-lab");
const a=JSON.parse(fs.readFileSync(root+"/gorge-data/gorge-seed-300.ui.json","utf8"));
const b=JSON.parse(fs.readFileSync(root+"/gorge-data/gorge-seed-301.ui.json","utf8"));
const cards=JSON.parse(fs.readFileSync(root+"/decks.json","utf8")).cards;
const lookup=name=>Object.values(cards).find(c=>c.name.toLowerCase()===name.toLowerCase())||null;
assert.equal(Dashboard.validate(a),a);
assert.equal(Dashboard.validate(b),b);
assert.equal(Dashboard.winner(a),0);
assert.equal(Dashboard.winner(b),3);
assert.equal(a.decks[Dashboard.winner(a)],"mortarion_current");
assert.equal(b.decks[Dashboard.winner(b)],"avengers-assemble");
assert.equal(Dashboard.seatForObject(1),0);
assert.equal(Dashboard.seatForObject(100),0);
assert.equal(Dashboard.seatForObject(101),1);
assert.equal(Dashboard.seatForObject(200),1);
assert.equal(Dashboard.seatForObject(201),2);
assert.equal(Dashboard.seatForObject(300),2);
assert.equal(Dashboard.seatForObject(301),3);
assert.equal(Dashboard.seatForObject(400),3);
assert.equal(Dashboard.seatForObject(503),null);
const stats=Dashboard.analyze([a,b],"mortarion_current");
assert.equal(stats.n,1);
assert.equal(stats.wins,1);
assert.equal(stats.winPct,100);
assert.equal(stats.losses,0);
assert(stats.cast.some(c=>c.name==="Sol Ring"&&c.gamesPlayed===1));
assert(stats.allCasts>0);
assert.equal(Dashboard.analyze([a,b],"magnus_premium").n,2);
assert.equal(Dashboard.analyze([a,b],"magnus_premium").wins,0);
assert.equal(Dashboard.analyze([a,b],"avengers-assemble").wins,1);
assert.equal(Dashboard.analyze([a,b],"wretched_ranks").wins,0);
assert.equal(Dashboard.analyze([a,b],"not-a-deck").n,0);
assert.equal(Dashboard.lifeRows(a).length,38);
assert.equal(Dashboard.lifeRows(b)[0].life.every(v=>v===40),true);
assert.equal(Dashboard.lifeRows(a)[0].hands.every(v=>v===7),true);
const all=Dashboard.castModel(stats,"all",lookup);
assert(all&&all.contenders.length);
assert(all.contenders.every(c=>c.metrics.some(m=>m.id==="turn")));
const creatures=Dashboard.castModel(stats,"creature",lookup);
assert(creatures&&creatures.contenders.every(c=>/Creature/i.test(c.card?.type_line||"")));
const invalid=structuredClone(a);invalid.snapshots[0].players[0].zones.hand=[];
assert.throws(()=>Dashboard.validate(invalid),/private|Invalid/);
const invalidLife=structuredClone(a);invalidLife.snapshots[0].players[0].life=20;
assert.throws(()=>Dashboard.validate(invalidLife),/40-life/);
const invalidWinner=structuredClone(a);
invalidWinner.turns.at(-1).events.at(-1).player=3;
assert.throws(()=>Dashboard.validate(invalidWinner),/winner/);
const html=fs.readFileSync(path.resolve(__dirname,"../web/pages/index.html"),"utf8");
const original=["simulation-snapshot","key-insights-panel","long-game-panel",
  "turn-reviewer-panel","development-panel","gorge-replay-panel"];
for(const id of original)assert(html.includes('id="'+id+'"'),"Original panel missing: "+id);
assert(html.includes('gorge_dashboard.js'),"Dashboard not linked in existing UI");
const exporter=fs.readFileSync(path.resolve(__dirname,"../tools/build_pages_deck_lab.py"),"utf8");
assert(exporter.includes('"gorge_dashboard.js"'),"Dashboard not in static build");
const app=fs.readFileSync(path.resolve(__dirname,"../web/pages/app.js"),"utf8");
assert(app.includes("window.GorgeDashboard?.setDeck(selected)"),
  "Original commander selection no longer wired into gorge");
console.log("PASS real gorge dashboard: 2 native games, winner, 40-life, source casts, original visual component IDs");
